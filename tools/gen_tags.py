"""Generate crates/rvt-core/src/tags_gen.rs from the clean-room reader's TAG_MAP and version tables.

The clean-room reader (rvtread.py) is the reference implementation; this keeps the Rust tables
identical to it. Usage: python -I gen_tags.py <path to analysis/rvtlab> <output .rs>
"""
import os
import sys

sys.path.insert(0, sys.argv[1])
import rvtread as R  # noqa: E402

out = ["// Generated by tools/gen_tags.py from the clean-room reader (rvtread.py). Do not edit.", ""]
out.append("/// Canonical (2026) class tag -> tag in another version (appendix A, step 239 and later).")
out.append("pub static TAG_MAP: &[(u16, &[(u16, u16)])] = &[")
for ver in sorted(R.TAG_MAP):
    pairs = ", ".join(f"({k}, {v})" for k, v in sorted(R.TAG_MAP[ver].items()))
    out.append(f"    ({ver}, &[{pairs}]),")
out.append("];")
out.append("")
out.append("/// u16 @12 of a 64-bit chain -> Revit version (section 1.3).")
out.append("pub static VERSIONS64: &[(u16, u16)] = &[" + ", ".join(f"(0x{k:04X}, {v})" for k, v in sorted(R.VERSIONS64.items())) + "];")
out.append("/// u16 @8 of a 32-bit chain -> Revit version (section 1.3).")
out.append("pub static VERSIONS32: &[(u16, u16)] = &[" + ", ".join(f"(0x{k:04X}, {v})" for k, v in sorted(R.VERSIONS32.items())) + "];")
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("tags:", {v: len(m) for v, m in R.TAG_MAP.items()}, "versions:", len(R.VERSIONS64), len(R.VERSIONS32))
