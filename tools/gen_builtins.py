"""Generate crates/rvt-model/src/builtins/data.rs from the export of oracle_builtins_revit.py.

Usage: python -I gen_builtins.py <exports dir with builtins.json> <output .rs>
"""
import json
import os
import sys


def rows(table):
    seen = {}
    for value, name, label in sorted(table, key=lambda r: r[0]):
        seen.setdefault(value, (name, label))  # enum aliases: the first name
    for value, (name, label) in sorted(seen.items()):
        text = "None" if label is None else f"Some({json.dumps(label, ensure_ascii=False)})"
        yield f"    Builtin {{ id: {value}, name: {json.dumps(name)}, label: {text} }},"


data = json.load(open(os.path.join(sys.argv[1], "builtins.json"), encoding="utf-8"))
out = ["// Generated by tools/gen_builtins.py from public API output. Do not edit.", "", "use super::Builtin;", ""]
for key, const in (("parameters", "PARAMETERS"), ("categories", "CATEGORIES")):
    out.append(f"pub static {const}: &[Builtin] = &[")
    out.extend(rows(data[key]))
    out.extend(["];", ""])
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(out))
print({k: len(v) for k, v in data.items()})
